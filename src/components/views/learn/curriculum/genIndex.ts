/**
 * Regenerates indexData.ts (light lesson index) from the full curriculum.
 * Run: npx tsx src/components/views/learn/curriculum/genIndex.ts
 */
import { writeFileSync } from 'node:fs';
import { estimateLessonReadMinutes } from '../academyUtils';
import { CURRICULUM } from './index';
import type { LevelMeta } from './types';

export function buildIndex(): LevelMeta[] {
  return CURRICULUM.map((lvl) => ({
    id: lvl.id,
    number: lvl.number,
    title: lvl.title,
    goal: lvl.goal,
    lessons: lvl.lessons.map((l) => ({
      id: l.id,
      title: l.title,
      objective: l.objective,
      quizCount: l.quiz.length,
      minutes: estimateLessonReadMinutes(l),
      ...(l.instrumentIds?.length ? { instrumentIds: l.instrumentIds } : {}),
    })),
  }));
}

if (process.argv[1]?.endsWith('genIndex.ts')) {
  const body = `// GENERATED by genIndex.ts - do not edit by hand. Kept in sync by indexSync.test.ts.
import type { LevelMeta } from './types';

export const CURRICULUM_INDEX: readonly LevelMeta[] = ${JSON.stringify(buildIndex(), null, 1)};
`;
  writeFileSync(new URL('./indexData.ts', import.meta.url), body);
  console.log('wrote indexData.ts');
}
